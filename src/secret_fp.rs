//! The keyed fingerprint a plane reports for each shared secret it holds (FEI-40).
//!
//! Services share secrets in pairs; a wrong value on one side used to surface only as refusals
//! later. Each plane reports, in its posture report, a fingerprint per relationship it takes part in,
//! and the deploy-time verifier (feir-os `deploy/posture/verify-posture.sh`) compares the pairs.
//!
//! `fingerprint(secret, relationship)` = lowercase hex of the first 16 bytes of
//! HMAC-SHA256(key = secret, message = `"feir-secret-alignment/v1:" + relationship`).
//!
//! It is not the secret and does not reveal it, but it is only as private as the secret is strong:
//! a fingerprint lets someone who holds it test guesses for a low-entropy secret offline. The report
//! that carries it is served only behind the operator credential. The golden vectors
//! (`vectors/secret-fingerprint.v1.json`, owned by feir-os, generated by an independent Python
//! reference) pin the construction across every plane.

use hmac::{Hmac, KeyInit, Mac};
use sha2::Sha256;

type HmacSha256 = Hmac<Sha256>;

const LABEL_PREFIX: &str = "feir-secret-alignment/v1:";

/// The fingerprint of `secret` for `relationship`, or `None` for an empty secret (an unset secret
/// has no fingerprint: the caller omits the relationship).
pub fn fingerprint(secret: &str, relationship: &str) -> Option<String> {
    if secret.is_empty() {
        return None;
    }
    let mut mac = <HmacSha256 as KeyInit>::new_from_slice(secret.as_bytes())
        .expect("HMAC accepts any key length");
    mac.update(LABEL_PREFIX.as_bytes());
    mac.update(relationship.as_bytes());
    let tag = mac.finalize().into_bytes();
    Some(hex::encode(&tag[..16]))
}

#[cfg(test)]
mod tests {
    use super::*;

    const VECTORS: &str = include_str!("../vectors/secret-fingerprint.v1.json");

    /// The fingerprint reproduces every golden vector from the independent Python reference.
    #[test]
    fn fingerprint_matches_the_golden_vectors() {
        let v: serde_json::Value = serde_json::from_str(VECTORS).unwrap();
        assert_eq!(v["label_prefix"], LABEL_PREFIX);
        let cases = v["cases"].as_array().unwrap();
        assert!(cases.len() >= 8, "only {} vectors", cases.len());
        for c in cases {
            let got = fingerprint(
                c["secret"].as_str().unwrap(),
                c["relationship"].as_str().unwrap(),
            );
            assert_eq!(
                got.as_deref(),
                c["fingerprint"].as_str(),
                "vector {}",
                c["name"]
            );
        }
    }

    #[test]
    fn shape_relationship_separation_and_empty() {
        let a = fingerprint("s", "leria-outbox").unwrap();
        assert_eq!(a.len(), 32);
        assert!(a
            .bytes()
            .all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b)));
        assert_ne!(a, fingerprint("s", "vultrino-outbox-poll").unwrap());
        assert_ne!(a, fingerprint("s2", "leria-outbox").unwrap());
        assert_eq!(fingerprint("", "leria-outbox"), None);
    }
}
